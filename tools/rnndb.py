import json
import os
import sys
import xml.etree.ElementTree as ET

RNNDB = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                     "reference", "envytools", "rnndb")
CHIP = "GK110B"
CHIPS = """NV1 NV3 NV3T NV4 NV5 NV10 NV15 NV1A NV11 NV17 NV1F NV18 NV20 NV25 NV30 NV35
NV31 NV36 NV34 NV40 NV41 NV43 NV44 NV44A C51 G70 G71 G72 G73 NV50 G80 G84 G86 G92 G94
G96 G98 G200 MCP77 MCP79 GT215 GT216 GT218 MCP89 GF100 GF104 GF106 GF108 GF110 GF114
GF116 GF119 GF117 GK104 GK107 GK106 GK110 GK110B GK208 GK20A GM107 GM108 GM200 GM204
GM206 GM20B GP100 GP102 GP104 GP106 GP107 GP108 GV100 TU102""".split()
NS = "{http://nouveau.freedesktop.org/}"
_db = None


def _num(v, default=0):
    return int(v, 0) if v is not None else default


def _valid(el):
    """True when the variants attribute of el includes CHIP."""
    v = el.get("variants")
    if v is None:
        return True
    if el.get("varset", "chipset") != "chipset":
        return False
    me = CHIPS.index(CHIP)
    for part in v.split():
        if ":" in part:
            lo, hi = part.split(":")
        elif part.endswith("-"):
            lo, hi = part[:-1], ""
        elif part.startswith("-"):
            lo, hi = "", part[1:]
        else:
            lo, hi = part, None
        if (lo and lo not in CHIPS) or (hi and hi not in CHIPS):
            continue
        a = CHIPS.index(lo) if lo else 0
        b = a + 1 if hi is None else (CHIPS.index(hi) if hi else len(CHIPS))
        if a <= me < b:
            return True
    return False


def _load():
    files, seen, queue = [], set(), ["nv_mmio.xml"]
    while queue:
        rel = queue.pop(0)
        path = os.path.normpath(os.path.join(RNNDB, rel))
        if path in seen or not os.path.exists(path):
            continue
        seen.add(path)
        root = ET.parse(path).getroot()
        files.append((os.path.relpath(path, RNNDB), root))
        for imp in root.iter(NS + "import"):
            queue.append(imp.get("file"))  # import paths are relative to rnndb/
    db = {"bitsets": {}, "groups": {}, "regs": []}
    for rel, root in files:
        for bs in root.iter(NS + "bitset"):
            db["bitsets"].setdefault(bs.get("name"), bs)
        for g in root.iter(NS + "group"):
            db["groups"].setdefault(g.get("name"), g)
    for rel, root in files:
        for dom in root.findall(NS + "domain"):
            if dom.get("name") == "NV_MMIO" and _valid(dom):
                _walk(db, dom, rel, 0, [], [])
    return db


def _walk(db, parent, rel, base, names, dims):
    for el in parent:
        tag = el.tag.replace(NS, "")
        if not _valid(el):
            continue
        if tag == "use-group":
            g = db["groups"].get(el.get("name"))
            if g is not None:
                _walk(db, g, rel, base, names, dims)
        elif tag in ("array", "stripe"):
            n = names + ([el.get("name")] if el.get("name") else [])
            d = dims + ([(_num(el.get("stride")), _num(el.get("length"), 1))]
                        if _num(el.get("length"), 1) > 1 else [])
            _walk(db, el, rel, base + _num(el.get("offset")), n, d)
        elif tag in ("reg8", "reg16", "reg32", "reg64"):
            width = int(tag[3:])
            length = _num(el.get("length"), 1)
            d = dims + ([(_num(el.get("stride"), width // 8), length)] if length > 1 else [])
            db["regs"].append({"name": ".".join(names + [el.get("name")]), "base": base + _num(el.get("offset")),
                               "dims": d, "width": width, "file": rel, "el": el})


def _fields(db, el, depth=0):
    out = []
    src = [el]
    if el.get("type") in db["bitsets"] and depth < 3:
        src.append(db["bitsets"][el.get("type")])
    for s in src:
        for bf in s.findall(NS + "bitfield"):
            if not _valid(bf):
                continue
            lo = _num(bf.get("pos"), _num(bf.get("low")))
            hi = _num(bf.get("pos"), _num(bf.get("high"), lo))
            out.append({"name": bf.get("name"), "shift": lo, "width": hi - lo + 1})
    return sorted(out, key=lambda f: (f["shift"], f["name"]))


def _match(reg, addr):
    """Indices of addr in the array dimensions of reg, or None."""
    off, index = addr - reg["base"], []
    if off < 0:
        return None
    for stride, length in reg["dims"]:
        if stride <= 0:
            return None
        i = off // stride
        if i >= length:
            return None
        index.append(i)
        off -= i * stride
    return index if off == 0 else None


def lookup(addr):
    """Definition of the register at addr for GK110B, or None."""
    global _db
    if _db is None:
        _db = _load()
    if isinstance(addr, str):
        addr = int(addr, 16)
    best = None
    for reg in _db["regs"]:
        index = _match(reg, addr)
        if index is None:
            continue
        # prefer 32-bit registers and the smallest element (a real register,
        # not a memory window such as PMEM)
        key = (reg["width"] != 32, len(reg["dims"]), reg["name"])
        if best is None or key < best[0]:
            best = (key, reg, index)
    if best is None:
        return None
    _, reg, index = best
    base = addr - sum(i * s for i, (s, _) in zip(index, reg["dims"]))
    return {"name": reg["name"], "address": "0x%06x" % addr, "base": "0x%06x" % base, "index": index,
            "width": reg["width"], "file": reg["file"], "fields": _fields(_db, reg["el"])}


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    for a in sys.argv[1:]:
        print(json.dumps(lookup(a)))
