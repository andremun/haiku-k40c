#!/usr/bin/env python3
"""Look up MMIO register names in the envytools register database.

    tools/rnndb.py 0x002100 0x409c24     print one JSON object per address
    import rnndb; rnndb.lookup(0x2100)   the same as a dict, or None

The database is reference/envytools/rnndb (the files that nv_mmio.xml
imports). Only definitions that are valid for the K40c chip (GK110B) are
used. A result is:

    {"name": "PFIFO.INTR", "address": "0x002100", "base": "0x002100",
     "index": [], "width": 32, "file": "fifo/gf100_pfifo.xml",
     "fields": [{"name": "BIND_ERROR", "shift": 0, "width": 1}, ...]}

`base` is the address of element 0 when the register is in an array, and
`index` has the array indices of this address. `file` is relative to
reference/envytools/rnndb/. No result means that the database has no
definition: do not invent a name.

Written by the scaffold (2026-10-11). The chipset order is fixed in CHIPS
because nvchipsets.xml is generated by the envytools build and is not in
the reference tree.
"""
